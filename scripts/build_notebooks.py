"""Generate the three self-contained Kaggle notebooks from src/, experiments/, splits/ and tests/.

    python scripts/build_notebooks.py [--user YOUR_KAGGLE_USERNAME] [--public]

The Kaggle username is a parameter (--user, or the KAGGLE_USERNAME environment variable);
the committed notebooks use the placeholder YOUR_KAGGLE_USERNAME. No credentials are
written anywhere: the Kaggle CLI reads its own token from ~/.kaggle/kaggle.json, and a
Hugging Face token is optional (all models and OOOK-Eval-Final are public); if you add one
as a Kaggle secret named HF_TOKEN, the notebook picks it up at run time.

Each kernel folder gets kernel-metadata.json (private by default, GPU on, internet on -
needed for the Zenodo and Hugging Face downloads) and one .ipynb that writes the exact
source files into /kaggle/working and runs one experiment. Re-run after any code change.
"""
from __future__ import annotations

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PIP = "pip install -q transformers==4.56.2 peft==0.17.1 jiwer==3.1.0"
PACKAGE = ["__init__.py", "textnorm.py", "metrics.py", "loops.py"]
EXPERIMENTS = ["data.py", "asr.py", "run_zeroshot.py", "run_finetune.py"]
PLACEHOLDER = "YOUR_KAGGLE_USERNAME"

KERNELS = {
    "sudanese-asr-zeroshot": dict(
        title="Sudanese ASR Zeroshot", config="zeroshot.json", script="run_zeroshot.py",
        about="Zero-shot Whisper small / medium / large-v2 / large-v3 / large-v3-turbo (+ the public "
              "AymanMansour/Whisper-Sudanese-Dialect-small checkpoint as an external reference) on the SDN "
              "speaker-disjoint test split and on OOOK-Eval-Final."),
    "sudanese-asr-ft-whisper-small": dict(
        title="Sudanese ASR FT Whisper Small", config="ft_whisper_small.json", script="run_finetune.py",
        about="Full fine-tune of whisper-small on SDN train; checkpoint chosen on DEV; test + OOOK-Eval decoded once."),
    "sudanese-asr-lora-turbo": dict(
        title="Sudanese ASR LoRA Turbo", config="lora_whisper_large_v3_turbo.json", script="run_finetune.py",
        about="LoRA (r=32) on whisper-large-v3-turbo, SDN train; checkpoint chosen on DEV; test + OOOK-Eval decoded once."),
}

HF_SECRET_CELL = """# Optional: use a Hugging Face token stored as a Kaggle secret named HF_TOKEN (not required).
import os
try:
    from kaggle_secrets import UserSecretsClient
    os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")
    print("HF_TOKEN loaded from Kaggle secrets")
except Exception:
    print("no HF_TOKEN secret; anonymous Hugging Face access")"""


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": text}


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def writefile(path, content):
    return code(f"%%writefile {path}\n{content}")


def build(slug, spec, user, private):
    w = "/kaggle/working"
    cells = [md(f"# {spec['title']}\n\n{spec['about']}\n\n"
                "Data: Mansour & Mukhtar, Sudanese dialect speech dataset, Zenodo 10.5281/zenodo.6869079 "
                "(v1.1, CC BY 4.0); Mansour (2026) OOOK-Eval-Final (evaluation only, not redistributed).\n\n"
                "Generated by `scripts/build_notebooks.py` from the sudanese-asr-eval repository. Do not edit by hand."),
             code(f"!{PIP}\n!mkdir -p {w}/src/sudanese_asr_eval {w}/configs {w}/splits {w}/tests {w}/outputs\n!nvidia-smi"),
             code(HF_SECRET_CELL)]
    for m in PACKAGE:
        cells.append(writefile(f"{w}/src/sudanese_asr_eval/{m}", read("src", "sudanese_asr_eval", m)))
    for m in EXPERIMENTS:
        cells.append(writefile(f"{w}/src/{m}", read("experiments", m)))
    cells.append(writefile(f"{w}/tests/test_textnorm.py", read("tests", "test_textnorm.py")))
    cells.append(writefile(f"{w}/splits/sdn_split_v1.tsv", read("splits", "sdn_split_v1.tsv")))
    cells.append(writefile(f"{w}/configs/{spec['config']}", read("experiments", "configs", spec["config"])))
    log = f"{w}/outputs/log_{slug}.txt"
    cells.append(code(f"!cd {w}/tests && PYTHONPATH={w}/src python -m unittest -v test_textnorm && "
                      f"cd {w}/src && PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True "
                      f"python -u {spec['script']} --config ../configs/{spec['config']} 2>&1 | tee {log}"))
    cells.append(code(f"!cp {w}/splits/sdn_split_v1.tsv {w}/configs/*.json {w}/outputs/ "
                      f"&& pip freeze > {w}/outputs/pip_freeze.txt && ls -la {w}/outputs"))
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    d = os.path.join(ROOT, "notebooks", "kaggle", slug)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, f"{slug}.ipynb"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(nb, f, ensure_ascii=False, indent=1)
        f.write("\n")
    meta = {"id": f"{user}/{slug}", "title": spec["title"], "code_file": f"{slug}.ipynb", "language": "python",
            "kernel_type": "notebook", "is_private": private, "enable_gpu": True, "enable_tpu": False,
            "enable_internet": True, "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
            "model_sources": []}
    with open(os.path.join(d, "kernel-metadata.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(meta, f, indent=2)
        f.write("\n")
    print("built", d)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default=os.environ.get("KAGGLE_USERNAME", PLACEHOLDER),
                    help="Kaggle username for kernel-metadata.json (default: $KAGGLE_USERNAME or a placeholder)")
    ap.add_argument("--public", action="store_true", help="mark the kernels public (default: private)")
    a = ap.parse_args()
    for slug, spec in KERNELS.items():
        build(slug, spec, a.user, private=not a.public)


if __name__ == "__main__":
    main()
